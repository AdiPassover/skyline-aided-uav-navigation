"""Build the two replay inputs a MARS-LVIG heading run needs, and nothing else (`DEC-VO-010`).

MARS-LVIG has **no usable barometric or flight-controller relative-altitude channel**:
``/dji_osdk_ros/height_above_takeoff`` is present and populated but reads 0.232 m on the ground and
then +/- 1e-6 m for the whole flight (`EXP-VO-013` B1). `EXP-VO-013` therefore stood an RTK-derived
takeoff-relative altitude in for the barometer, and this script writes exactly that series to a file
so a runtime replay can consume it through the ordinary ``takeoff_relative`` height semantics rather
than through a mislabelled oracle arm.

Two outputs per sequence, both small, both provenance-stamped in the header comment of the config
that reads them:

``<seq>-height-rtk-relative.csv``   ``timestamp_s,baro_relative_m`` = ``up_m - up_m[0]``
    A STAND-IN, not a barometer. It carries no sensor noise, drift, bias, quantisation or latency,
    and no claim about a real barometer may be derived from a run that uses it. On both flights the
    series is near-constant (height above the takeoff datum is constant to 0.030 m), which is why it
    is adequate for a heading experiment: it holds the scale channel still while the direction
    channel is the thing under test.

``<seq>-heading-fc.csv``            ``timestamp_s,yaw_compass_deg``
    A verbatim copy of ``datasets/<seq>/attitude.csv``'s two relevant columns, so the replay input
    is a self-contained file and the run manifest names something that will not be regenerated by an
    unrelated ingest. It is the flight controller's fused attitude yaw of the **AIRFRAME**; the
    navigation camera's heading is derived from it at runtime through the declared
    ``delta_mount_deg``.

Usage:  python evaluation/tools/vo_heading_runtime/make_replay_inputs.py
"""

from __future__ import annotations

import csv
import io
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[3]
OUT = ROOT / "evaluation" / "tools" / "vo_heading_runtime" / "inputs"

SEQUENCES = ("hkairport01-a", "amtown01-d")


def _rows(path: pathlib.Path) -> list[dict]:
    with io.open(path, encoding="utf-8") as f:
        return list(csv.DictReader(f))


def build(seq: str) -> None:
    ds = ROOT / "datasets" / seq
    gt = _rows(ds / "groundtruth.csv")
    att = _rows(ds / "attitude.csv")

    up0 = float(gt[0]["up_m"])
    height_path = OUT / f"{seq}-height-rtk-relative.csv"
    with io.open(height_path, "w", encoding="utf-8", newline="") as f:
        f.write("timestamp_s,baro_relative_m\n")
        for r in gt:
            f.write("%.9f,%.9f\n" % (float(r["timestamp_s"]), float(r["up_m"]) - up0))

    heading_path = OUT / f"{seq}-heading-fc.csv"
    with io.open(heading_path, "w", encoding="utf-8", newline="") as f:
        f.write("timestamp_s,yaw_compass_deg\n")
        for r in att:
            f.write("%.9f,%.4f\n" % (float(r["timestamp_s"]), float(r["yaw_compass_deg"])))

    rel = [float(r["up_m"]) - up0 for r in gt]
    print("%-16s height %5d rows, span %+.3f .. %+.3f m  |  heading %6d rows, %.1f Hz"
          % (seq, len(gt), min(rel), max(rel), len(att),
             (len(att) - 1) / (float(att[-1]["timestamp_s"]) - float(att[0]["timestamp_s"]))))


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    for seq in SEQUENCES:
        if not (ROOT / "datasets" / seq / "attitude.csv").exists():
            print("skipping %s: attitude.csv absent (ingest product)" % seq)
            continue
        build(seq)
    return 0


if __name__ == "__main__":
    sys.exit(main())
