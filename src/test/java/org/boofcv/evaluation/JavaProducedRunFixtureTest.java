package org.boofcv.evaluation;

import boofcv.struct.image.GrayF32;
import org.boofcv.stitching.StitchingEstimator;
import org.boofcv.stitching.StitchingFactory;
import org.junit.jupiter.api.Test;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.List;
import java.util.LinkedHashMap;
import java.util.Map;
import java.util.Random;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Generates and verifies {@code evaluation/tests/fixtures/java_produced_run/}, the fixture T047
 * uses to prove the Python reader recovers exact values written by the real Java capture path
 * (not a mock), closing the writer&harr;reader loop (contracts/run-record.md "Contract tests").
 *
 * <p>Deterministic: a fixed-seed synthetic textured "world" image is cropped with a fixed
 * per-frame integer-pixel shift, so the real {@link StitchingEstimator} over BoofCV's KLT/RANSAC
 * (whose seed is fixed inside BoofCV) produces the same output
 * on every run. Regenerating the fixture here on every test run, rather than hand-authoring it
 * once, is what proves the writer and the fixture cannot drift apart silently.
 */
public class JavaProducedRunFixtureTest {

    private static final int WORLD_SIZE = 300;
    private static final int FRAME_SIZE = 120;
    private static final int NUM_FRAMES = 6;
    private static final Path FIXTURE_DIR = Paths.get("evaluation", "tests", "fixtures", "java_produced_run");

    private static GrayF32 syntheticWorld() {
        GrayF32 world = new GrayF32(WORLD_SIZE, WORLD_SIZE);
        Random random = new Random(42);
        for (int y = 0; y < WORLD_SIZE; y++) {
            for (int x = 0; x < WORLD_SIZE; x++) {
                world.set(x, y, random.nextInt(256));
            }
        }
        return world;
    }

    private static GrayF32 crop(GrayF32 world, int offsetX, int offsetY) {
        GrayF32 frame = new GrayF32(FRAME_SIZE, FRAME_SIZE);
        for (int y = 0; y < FRAME_SIZE; y++) {
            for (int x = 0; x < FRAME_SIZE; x++) {
                frame.set(x, y, world.get(x + offsetX, y + offsetY));
            }
        }
        return frame;
    }

    private static class InMemoryFrameSource implements FrameSource {
        private final GrayF32 world = syntheticWorld();

        @Override
        public int frameCount() {
            return NUM_FRAMES;
        }

        @Override
        public TimestampedFrame frame(int index) {
            int offsetX = index * 3;
            int offsetY = index * 2;
            return new TimestampedFrame(index, index * 0.1, crop(world, offsetX, offsetY));
        }
    }

    @Test
    public void testJavaProducedFixtureRegeneratesDeterministically() throws IOException {
        StitchingEstimator<GrayF32> estimator = new StitchingEstimator<>(StitchingFactory.defaultGray());
        VoRunner runner = new VoRunner(estimator, new InMemoryFrameSource());

        RunManifest manifest = new RunManifest();
        manifest.runId = "java-produced-fixture";
        manifest.datasetId = "java-produced-fixture-dataset";
        manifest.datasetRevision = "v1";
        manifest.estimatorId = "stitching-vo";
        manifest.estimatorVersion = "test-fixture";
        manifest.evaluatorCaptureVersion = "test-fixture";
        // LinkedHashMap, not Map.of: Map.of randomises iteration order per JVM instance, so the
        // committed fixture's manifest churned between otherwise-identical `gradlew test` runs and
        // left the tree dirty for no reason. Insertion order is stable, so re-running the suite is
        // now a no-op on a clean tree unless the estimator's output actually changed.
        Map<String, Object> estimatorConfig = new LinkedHashMap<>();
        estimatorConfig.put("shrinkScale", 0.5);
        estimatorConfig.put("note",
                "generated by JavaProducedRunFixtureTest using StitchingFactory.defaultGray()");
        manifest.estimatorConfig = estimatorConfig;
        manifest.environment = new Environment(
                "test-host", "test-os", "test-cpu", System.getProperty("java.version", "unknown"), 1024, false);
        manifest.runTimestamp = "2026-08-12T00:00:00Z";

        try (RunRecordWriter writer = new RunRecordWriter(FIXTURE_DIR, manifest, NUM_FRAMES)) {
            runner.run(writer);
        }

        List<String> lines = Files.readAllLines(FIXTURE_DIR.resolve("frames.csv"));
        assertEquals(NUM_FRAMES + 1, lines.size(), "header plus one row per frame");
        assertTrue(lines.get(1).startsWith("0,0.0,"), "frame 0 must be the init row");
        String[] firstRowCols = lines.get(1).split(",", -1);
        assertEquals("init", firstRowCols[7]);
        assertEquals("0", firstRowCols[8]);
    }
}
